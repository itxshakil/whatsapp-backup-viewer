/// <reference lib="webworker" />
declare const self: ServiceWorkerGlobalScope;

import { cleanupOutdatedCaches, precacheAndRoute } from 'workbox-precaching';
import { clientsClaim } from 'workbox-core';
import { SHARED_FILE_CACHE, SHARED_FILE_NAME_HEADER, SHARED_FILE_URL } from './utils/incomingFiles';

// The manifest's share_target posts the exported chat here. Registered before Workbox's
// listener, which only answers GET requests anyway.
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method === 'POST' && url.pathname === '/share') {
    event.respondWith(receiveSharedFile(event.request));
  }
});

async function receiveSharedFile(request: Request): Promise<Response> {
  const formData = await request.formData();
  const file = formData.getAll('chat').find((entry): entry is File => entry instanceof File);

  if (file) {
    const cache = await caches.open(SHARED_FILE_CACHE);
    await cache.put(SHARED_FILE_URL, new Response(file, {
      headers: {
        'Content-Type': file.type || 'application/octet-stream',
        [SHARED_FILE_NAME_HEADER]: encodeURIComponent(file.name),
      },
    }));
  }

  return Response.redirect('/?shared=1', 303);
}

// Precache all assets generated by Vite
precacheAndRoute(self.__WB_MANIFEST || []);

// Cleanup old caches
cleanupOutdatedCaches();

// Take control of all clients immediately
self.skipWaiting();
clientsClaim();
